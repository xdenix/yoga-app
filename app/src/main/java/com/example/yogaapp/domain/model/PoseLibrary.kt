    /** Lookup helper — returns the matching pose or null for an unknown id. */
    fun byId(id: String): YogaPose? = all.firstOrNull { it.id == id }

    /** Poses suitable for a given level — used by the plan generator. */
    fun forLevel(level: YogaLevel): List<YogaPose> = when (level) {
        YogaLevel.Beginner -> all.filter { it.level == YogaLevel.Beginner }
        YogaLevel.Intermediate -> all.filter {
            it.level == YogaLevel.Beginner || it.level == YogaLevel.Intermediate
        }
        YogaLevel.Advanced -> all
    }

    private fun pose(
        id: String,
        sanskrit: String,
        ru: String,
        en: String,
        ruDesc: String,
        enDesc: String,
        level: YogaLevel,
        focuses: List<BodyFocus>,
        duration: Int,
        spec: PoseSpec,
        bilateral: Boolean = false,
    ): YogaPose = YogaPose(
        id = id,
        sanskritName = sanskrit,
        ruName = ru,
        enName = en,
        ruDescription = ruDesc,
        enDescription = enDesc,
        level = level,
        focuses = focuses,
        defaultDurationSec = duration,
        spec = spec,
        audioAssetName = null, // TTS by default; audio pack can populate these.
        bilateral = bilateral,
    )
